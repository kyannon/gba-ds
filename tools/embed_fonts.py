#!/usr/bin/env python3
"""Embeds the UI fonts (assets/fonts) in src/fonts_data.c, zlib-compressed.

    tools/embed_fonts.py           # writes src/fonts_data.c
    tools/embed_fonts.py --check   # what it holds is the files in assets/fonts

Jost (https://github.com/indestructible-type/Jost) is under the SIL Open
Font License 1.1 (assets/fonts/Jost-OFL.txt), which allows bundling it. The
Chinese interfaces' fonts are Noto Sans SC and Noto Sans TC, under the same
licence (assets/fonts/NotoSansSC-OFL.txt, -TC-OFL.txt), cut down to the
characters the translations use by tools/make_zh_font.py.

The whole set is about 7 MB raw and about 4.5 MB deflated (the Chinese bold
faces carry a whole character set, for the names of the player's own ROMs), so
each one is stored as a zlib stream and src/textfont.c inflates it the first
time it draws with that face: about 200 KB for English's two, and only the
Chinese faces the language uses after that.

--check decodes what is committed and compares it with assets/fonts, so it
doesn't care which zlib wrote the stream (their output can differ in the
details); a normal run writes them again.
"""
import os
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [("jost_bold_italic", "Jost-700-BoldItalic.ttf"),
         ("jost_medium_italic", "Jost-500-MediumItalic.ttf"),
         ("noto_sans_sc_bold", "NotoSansSC-Bold-subset.ttf"),
         ("noto_sans_sc_regular", "NotoSansSC-Regular-subset.ttf"),
         ("noto_sans_tc_bold", "NotoSansTC-Bold-subset.ttf"),
         ("noto_sans_tc_regular", "NotoSansTC-Regular-subset.ttf")]
OUT = os.path.join(ROOT, "src", "fonts_data.c")


def read_font(name):
    with open(os.path.join(ROOT, "assets", "fonts", name), "rb") as f:
        return f.read()


def write():
    lines = ["/* Generated by tools/embed_fonts.py - do not edit.",
             " * Each font is a zlib stream (src/inflate.c decodes it; textfont.c",
             " * inflates a face the first time it draws with it).",
             " * Jost, SIL Open Font License 1.1: assets/fonts/Jost-OFL.txt",
             " * Noto Sans SC and TC (the Chinese interfaces' fonts, cut down to the",
             " * characters the translations use by tools/make_zh_font.py), SIL Open",
             " * Font License 1.1: assets/fonts/NotoSansSC-OFL.txt, -TC-OFL.txt */",
             '#include "fonts_data.h"', ""]
    for name, fn in FONTS:
        data = read_font(fn)
        packed = zlib.compress(data, 9)
        lines.append(f"static const unsigned char {name}_z[{len(packed)}] = {{")
        for i in range(0, len(packed), 24):
            lines.append("\t" + ",".join(str(b) for b in packed[i:i + 24]) + ",")
        lines.append("};")
        print(f"  {fn}: {len(data)} -> {len(packed)} bytes")
    lines.append("")
    lines.append("const EmbeddedFont embeddedFonts[EMBEDDED_FONT_COUNT] = {")
    for name, fn in FONTS:
        lines.append(f"\t{{ {name}_z, sizeof({name}_z), {len(read_font(fn))} }},")
    lines.append("};")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


def check():
    """The committed arrays decode to the fonts in assets/fonts."""
    with open(OUT, encoding="utf-8") as f:
        text = f.read()
    failed = False
    for name, fn in FONTS:
        want = read_font(fn)
        start = text.find(f"static const unsigned char {name}_z[")
        if start < 0:
            print(f"{fn}: {name}_z isn't in src/fonts_data.c")
            failed = True
            continue
        body = text[text.index("{", start) + 1:text.index("}", start)]
        packed = bytes(int(tok) for tok in body.replace("\n", "").replace("\t", "").split(",") if tok.strip())
        at = text.index(f"{{ {name}_z, sizeof({name}_z), ")
        raw = int(text[at:].split(",")[2].split("}")[0])
        try:
            got = zlib.decompress(packed)
        except zlib.error as e:
            print(f"{fn}: won't decode ({e})")
            failed = True
            continue
        if got != want or raw != len(want):
            print(f"{fn}: decodes to {len(got)} bytes, the file is {len(want)}")
            failed = True
        else:
            print(f"  {fn}: ok ({raw} bytes)")
    return 1 if failed else 0


if __name__ == "__main__":
    if "--check" in sys.argv[1:]:
        sys.exit(check())
    write()
