#!/usr/bin/env python3
"""Embeds the UI fonts (assets/fonts) in src/fonts_data.c.

    tools/embed_fonts.py

Jost (https://github.com/indestructible-type/Jost) is under the SIL Open
Font License 1.1 (assets/fonts/Jost-OFL.txt), which allows bundling it. The
Chinese interfaces' fonts are Noto Sans SC and Noto Sans TC, under the same
licence (assets/fonts/NotoSansSC-OFL.txt, -TC-OFL.txt), cut down to the
characters the translations use by tools/make_zh_font.py.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [("jost_bold_italic", "Jost-700-BoldItalic.ttf"),
         ("jost_medium_italic", "Jost-500-MediumItalic.ttf"),
         ("noto_sans_sc_bold", "NotoSansSC-Bold-subset.ttf"),
         ("noto_sans_sc_regular", "NotoSansSC-Regular-subset.ttf"),
         ("noto_sans_tc_bold", "NotoSansTC-Bold-subset.ttf"),
         ("noto_sans_tc_regular", "NotoSansTC-Regular-subset.ttf")]

lines = ["/* Generated by tools/embed_fonts.py - do not edit.",
         " * Jost, SIL Open Font License 1.1: assets/fonts/Jost-OFL.txt",
         " * Noto Sans SC and TC (the Chinese interfaces' fonts, cut down to the",
         " * characters the translations use by tools/make_zh_font.py), SIL Open",
         " * Font License 1.1: assets/fonts/NotoSansSC-OFL.txt, -TC-OFL.txt */",
         '#include "fonts_data.h"', ""]
for name, fn in FONTS:
    data = open(os.path.join(ROOT, "assets", "fonts", fn), "rb").read()
    lines.append(f"static const unsigned char {name}_ttf[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        lines.append("\t" + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
lines.append("")
lines.append("const EmbeddedFont embeddedFonts[EMBEDDED_FONT_COUNT] = {")
for name, _ in FONTS:
    lines.append(f"\t{{ {name}_ttf, sizeof({name}_ttf) }},")
lines.append("};")
with open(os.path.join(ROOT, "src", "fonts_data.c"), "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("src/fonts_data.c:", ", ".join(fn for _, fn in FONTS))
