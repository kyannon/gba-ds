#!/usr/bin/env python3
"""Embed the Scaling filter's upscalers (third_party/mgba-shaders) into
src/upscale_shaders.c (issue #89).

Each folder is one of mGBA's shader packs, copied unmodified: a manifest.ini
(one pass: its vertexShader, if any, its fragmentShader and its uniforms'
defaults) and the GLSL sources. The sources go in as C strings with their
licence headers, so the notices travel inside the program too.

  tools/embed_shaders.py          write src/upscale_shaders.c
  tools/embed_shaders.py --check  exit 1 if it is out of date (CI)
"""
import configparser
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "third_party", "mgba-shaders")
OUT = os.path.join(ROOT, "src", "upscale_shaders.c")

# the packs, in the order upscale.c refers to them (UP_PACK_* in upscale_shaders.h)
PACKS = ["hq2x", "mmpx", "xbr-lv2", "xbr-lv3", "omniscale"]

# Fixes for OpenGL ES, which (unlike the desktop GLSL these were written for)
# never turns a whole number into a decimal on its own: (pack, file, text,
# replacement, how many times it must appear). The files in third_party stay
# as mGBA has them; a fix whose text is gone stops the tool, so a new copy of
# a pack gets looked at again.
FIXES = [
    ("xbr-lv2", "xbr.fs", "(2 * delta", "(2.0 * delta", 4),
    ("omniscale", "omniscale.fs", "pixel_size / 2", "pixel_size / 2.0", 21),
]


def read_fixed(name, fname):
    text = open(os.path.join(SRC, name, fname)).read()
    for pk, fn, old, new, n in FIXES:
        if pk == name and fn == fname:
            if text.count(old) != n:
                sys.exit("%s/%s: expected %d of %r, found %d: look at the fix again" % (name, fname, n, old, text.count(old)))
            text = text.replace(old, new)
    return text


def c_string(text):
    out = []
    for line in text.replace("\r\n", "\n").split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t")
        out.append('\t"%s\\n"' % esc)
    return "\n".join(out)


def pack(name):
    d = os.path.join(SRC, name)
    ini = configparser.ConfigParser(interpolation=None)
    ini.optionxform = str
    ini.read(os.path.join(d, "manifest.ini"))
    if ini.getint("shader", "passes", fallback=1) != 1:
        sys.exit("%s: only one-pass shaders are supported" % name)
    p = ini["pass.0"]
    vs = p.get("vertexShader")
    fs = p["fragmentShader"]
    uniforms = []
    for sec in ini.sections():
        pre = "pass.0.uniform."
        if sec.startswith(pre):
            u = ini[sec]
            if u.get("type", "float") != "float":
                sys.exit("%s: uniform %s: only floats are supported" % (name, sec))
            uniforms.append((sec[len(pre):], float(u["default"])))
    ident = name.replace("-", "_")
    parts = []
    if vs:
        parts.append("static const char %s_vs[] =\n%s;\n" % (ident, c_string(read_fixed(name, vs))))
    parts.append("static const char %s_fs[] =\n%s;\n" % (ident, c_string(read_fixed(name, fs))))
    if uniforms:
        parts.append("static const UpscaleUniform %s_uniforms[] = {\n%s\n};\n" % (
            ident, "\n".join('\t{ "%s", %rf },' % (n, v) for n, v in uniforms)))
    entry = '\t{ "%s", %s, %s_fs, %s, %d },' % (
        ini["shader"].get("name", name), "%s_vs" % ident if vs else "NULL", ident,
        "%s_uniforms" % ident if uniforms else "NULL", len(uniforms))
    return "\n".join(parts), entry


def generate():
    body, entries = [], []
    for name in PACKS:
        b, e = pack(name)
        body.append("/* ---- %s (third_party/mgba-shaders/%s) */\n%s" % (name, name, b))
        entries.append(e)
    return (
        "/* Generated by tools/embed_shaders.py from third_party/mgba-shaders: don't\n"
        " * edit; run the tool again. mGBA's upscaling shaders, each under the MIT\n"
        " * license in its own header below (see that folder's README.md). */\n"
        '#include "upscale_shaders.h"\n\n#include <stddef.h>\n\n'
        + "\n".join(body)
        + "\nconst UpscalePack upscalePacks[UP_PACK_COUNT] = {\n" + "\n".join(entries) + "\n};\n")


def main():
    text = generate()
    if "--check" in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        if old != text:
            sys.exit("src/upscale_shaders.c is out of date: run tools/embed_shaders.py")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
