#!/usr/bin/env python3
"""Writes src/i18n_zh.[ch] (Simplified) and src/i18n_zt.[ch] (Traditional)
from assets/i18n/zh-CN.tsv and assets/i18n/zh-TW.tsv.

    tools/make_i18n.py            # write them
    tools/make_i18n.py --check    # only say what looks wrong (no files written)

A catalogue is one "English<TAB>Chinese" line per string, with # comments and
blank lines allowed. The English side is the string exactly as the code has it
(tr("...") in the code, or the whole text ui.c translates as it draws it), so a
line that isn't in the code any more, or that's a typo of one, is reported. Both
catalogues must have the same English lines.

A line may leave out the English's trailing %s or %d (Chinese has no plural
"s", say): printf ignores the arguments a format doesn't use. Nothing may be
reordered: a format's conversions must be the English's first ones.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
I18N = os.path.join(ROOT, "assets", "i18n")
CATALOGUES = [
    {"name": "Simplified", "file": "zh-CN.tsv", "c": "src/i18n_zh.c", "h": "src/i18n_zh.h",
     "table": "i18nZhTable", "count": "i18nZhCount"},
    {"name": "Traditional", "file": "zh-TW.tsv", "c": "src/i18n_zt.c", "h": "src/i18n_zt.h",
     "table": "i18nZtTable", "count": "i18nZtCount"},
]

CONV = re.compile(r"%(?:[-+ #0]*)(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|h|ll|l|j|z|t|L)?([diouxXeEfFgGaAcspn%])")


def conversions(s):
    return [m.group(1) for m in CONV.finditer(s) if m.group(1) != "%"]


def c_string(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 0x20:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def read_catalogue(path):
    entries, errors, warnings = [], [], []
    seen = {}
    with open(path, encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            if "\t" not in line:
                errors.append(f"{lineno}: no TAB: {line!r}")
                continue
            en, zh = line.split("\t", 1)
            if not en:
                errors.append(f"{lineno}: empty English side")
                continue
            if not zh.strip():
                errors.append(f"{lineno}: empty Chinese side: {en!r}")
                continue
            if en in seen:
                errors.append(f"{lineno}: {en!r} is already on line {seen[en]}")
                continue
            seen[en] = lineno
            a, b = conversions(en), conversions(zh)
            if b != a[: len(b)]:
                errors.append(f"{lineno}: the format's arguments don't match: {en!r} / {zh!r} ({a} / {b})")
            elif len(b) < len(a):
                warnings.append(f"{lineno}: leaves out the English's last arguments: {en!r}")
            entries.append((en, zh))
    return entries, errors, warnings


def unescape(s):
    """A C literal's bytes as text: \\xHH bytes are read as UTF-8, as the
    compiler does (some strings have \\xC2\\xB7, others the character)."""
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c != "\\" or i + 1 >= len(s):
            out += c.encode("utf-8")
            i += 1
            continue
        e = s[i + 1]
        if e == "n":
            out.append(10)
            i += 2
        elif e == "t":
            out.append(9)
            i += 2
        elif e == "r":
            out.append(13)
            i += 2
        elif e in ('"', "\\", "'"):
            out += e.encode("utf-8")
            i += 2
        elif e == "x":
            m = re.match(r"[0-9a-fA-F]{1,2}", s[i + 2:])
            if m:
                out.append(int(m.group(0), 16))
                i += 2 + len(m.group(0))
            else:
                out += c.encode("utf-8")
                i += 1
        else:
            out += (c + e).encode("utf-8")
            i += 2
    return out.decode("utf-8", "replace")


def source_strings():
    """Every string literal in src/*.c, joined where C joins them ("a" "b")."""
    lits = set()
    for fn in sorted(os.listdir(os.path.join(ROOT, "src"))):
        if not fn.endswith(".c"):
            continue
        text = open(os.path.join(ROOT, "src", fn), encoding="utf-8", errors="replace").read()
        if text.startswith("/* Generated by tools/"):
            continue  # (this file and the others the tools write)
        text = re.sub(r"\\\s*\n\s*", "", text)  # line continuations
        for m in re.finditer(r'"((?:[^"\\]|\\.)*)"(\s*"((?:[^"\\]|\\.)*)")*', text):
            parts = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(0))
            lits.add(unescape("".join(parts)))
    return lits


def write_table(cat, entries):
    count = len(entries)
    guard = "GBADS_" + os.path.basename(cat["h"]).upper().replace(".", "_")
    h = [
        "/* Generated by tools/make_i18n.py - do not edit.",
        f" * The {cat['name'].lower()} Chinese interface: assets/i18n/{cat['file']} has",
        " * the text, in strcmp order for i18n.c's bsearch. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        '#include "i18n.h"',
        "",
        "#include <string.h>",
        "",
        f"extern const I18nEntry {cat['table']}[];",
        f"extern const int {cat['count']}; /* {count} */",
        "",
        "#endif",
        "",
    ]
    c = [
        "/* Generated by tools/make_i18n.py - do not edit.",
        f" * The {cat['name'].lower()} Chinese interface: assets/i18n/{cat['file']} has the text. */",
        f'#include "{os.path.basename(cat["h"])}"',
        "",
        f"const I18nEntry {cat['table']}[] = {{",
    ]
    for en, zh in sorted(entries, key=lambda e: e[0]):
        c.append(f"\t{{ {c_string(en)}, {c_string(zh)} }},")
    c += ["};", f"const int {cat['count']} = (int) (sizeof({cat['table']}) / sizeof({cat['table']}[0]));", ""]
    # (newline="": no translation: the repo is LF, and CI regenerates on Linux)
    open(os.path.join(ROOT, cat["h"]), "w", encoding="utf-8", newline="\n").write("\n".join(h))
    open(os.path.join(ROOT, cat["c"]), "w", encoding="utf-8", newline="\n").write("\n".join(c))


def tr_calls():
    """Every tr("...") in the code: those strings must be in the catalogues."""
    found = []
    for fn in sorted(os.listdir(os.path.join(ROOT, "src"))):
        if not fn.endswith(".c"):
            continue
        text = open(os.path.join(ROOT, "src", fn), encoding="utf-8", errors="replace").read()
        if text.startswith("/* Generated by tools/"):
            continue
        text = re.sub(r"\\\s*\n\s*", "", text)
        for m in re.finditer(r'\btr\s*\(\s*"((?:[^"\\]|\\.)*)"\s*\)', text):
            found.append((fn, unescape(m.group(1))))
    return found


def main():
    check_only = "--check" in sys.argv
    failed = False
    catalogues, errors_all = {}, []
    for cat in CATALOGUES:
        entries, errors, warnings = read_catalogue(os.path.join(I18N, cat["file"]))
        for w in warnings:
            print(f"{cat['file']} warning: {w}")
        for e in errors:
            print(f"{cat['file']} error: {e}")
            failed = True
        catalogues[cat["file"]] = entries

    # the same English lines in both
    first = CATALOGUES[0]["file"]
    keys = {en for en, _ in catalogues[first]}
    for cat in CATALOGUES[1:]:
        other = {en for en, _ in catalogues[cat["file"]]}
        for en in sorted(keys - other):
            print(f"{cat['file']}: missing (it's in {first}): {en!r}")
            failed = True
        for en in sorted(other - keys):
            print(f"{cat['file']}: not in {first}: {en!r}")
            failed = True

    lits = source_strings()
    for cat in CATALOGUES:
        for en, _ in catalogues[cat["file"]]:
            if en not in lits:
                print(f"{cat['file']}: not in the code: {en}")
                failed = True

    # a tr("...") with no catalogue line would silently stay in English
    known = {en for en, _ in catalogues[CATALOGUES[0]["file"]]}
    for fn, en in tr_calls():
        if en not in known:
            print(f"src/{fn}: tr() of a string no catalogue has: {en!r}")
            failed = True

    for cat in CATALOGUES:
        zh = "".join(v for _, v in catalogues[cat["file"]])
        print(f"{cat['file']}: {len(catalogues[cat['file']])} strings, "
              f"{len({c for c in zh if ord(c) > 0x7F})} Chinese characters")
    if failed:
        print("not written: fix the errors first")
        return 1
    if check_only:
        return 0
    for cat in CATALOGUES:
        write_table(cat, catalogues[cat["file"]])
        print("wrote", cat["c"], "and", cat["h"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
