def gen_headers(work):
    rows = []
    for c in range(32, 127):
        g = FONT.get(chr(c), FONT[" "]).split()
        rows.append("{" + ",".join(str(int(r, 2)) for r in g) + "}")
    with open(os.path.join(work, "font.h"), "w") as f:
        f.write("/* generated by build.py */\nstatic const unsigned char font5x7[95][7] = {\n\t" + ",\n\t".join(rows) + "\n};\n")
    sine = [round(4096 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
    with open(os.path.join(work, "sine.h"), "w") as f:
        f.write("/* generated by build.py: sin, 1.0 = 4096 */\nstatic const short sine[256] = {" + ",".join(map(str, sine)) + "};\n")


def run(*cmd):
    subprocess.run(cmd, check=True)


def main():
    root = os.path.abspath(os.path.join(HERE, "..", ".."))
    out = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(root, "build", "widetest")
    work = os.path.join(out, "obj")
    os.makedirs(work, exist_ok=True)
    gen_headers(work)
    cflags = ["--target=armv4t-none-eabi", "-mcpu=arm7tdmi", "-O2", "-ffreestanding", "-fno-builtin",
              "-nostdlib", "-Wall", "-Wextra", "-I", work]
    run("clang", "--target=armv4t-none-eabi", "-mcpu=arm7tdmi", "-c", os.path.join(HERE, "crt0.s"), "-o", os.path.join(work, "crt0.o"))
    run("clang", *cflags, "-mthumb", "-c", os.path.join(HERE, "widetest.c"), "-o", os.path.join(work, "widetest.o"))
    elf = os.path.join(work, "widetest.elf")
    run("ld.lld", "-T", os.path.join(HERE, "widetest.ld"), "--no-undefined", os.path.join(work, "crt0.o"),
        os.path.join(work, "widetest.o"), "-o", elf)
    secs = subprocess.run(["llvm-objdump", "-h", elf], capture_output=True, text=True, check=True).stdout
    if " .data" in secs:
        sys.exit("widetest.c has initialised data (.data): crt0.s doesn't copy it; set it in main")
    binf = os.path.join(work, "widetest.bin")
    run("llvm-objcopy", "-O", "binary", "--only-section=.crt0", "--only-section=.widemarker",
        "--only-section=.text", elf, binf)
    rom = bytearray(open(binf, "rb").read())
    rom[0xA0:0xAC] = TITLE
    rom[0xAC:0xB0] = CODE
    rom[0xB0:0xB2] = b"00"
    rom[0xB2] = 0x96
    rom[0xBD] = (-(sum(rom[0xA0:0xBD]) + 0x19)) & 0xFF
    assert rom[MARKER_AT:MARKER_AT + 32] == b"\xff" * 32, "the marker's place moved"
    rom += b"\xff" * (-len(rom) % 0x1000)
    gba = os.path.join(out, NAME + ".gba")
    open(gba, "wb").write(rom)
    print(f"{gba}: {len(rom)} bytes")
    for r in RATIOS:
        num, den = widescreen.parse_ratio(r)
        ips = os.path.join(out, f"{NAME} ({num}-{den}).ips")
        open(ips, "wb").write(widescreen.ips_write([(MARKER_AT, widescreen.marker(num, den), False)]))
        print(f"{ips}: {r}, {'%d x %d' % widescreen.picture(num, den)}")


if __name__ == "__main__":
    main()
