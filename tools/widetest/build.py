HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import widescreen  # noqa: E402

NAME = "GBA DS Widescreen Test"
TITLE = b"GBADS WIDE\0\0"
CODE = b"ZWSE"
MARKER_AT = 0x200  # widetest.ld .widemarker
RATIOS = ["16:9", "16:10", "4:3"]

